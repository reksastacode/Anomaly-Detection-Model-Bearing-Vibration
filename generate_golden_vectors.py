"""
ZENTRA TinyML - Golden Test Vector Generator (Tahap 12)
Selects 1 Normal and 1 Fault test window, computes reference Python features,
standardization, and PCA reconstruction score, and exports a C header for
bit-exact embedded parity verification on ESP32-S3.
"""

import numpy as np
from pathlib import Path
from src.features import extract_features_single_window
import json

def generate_golden_vectors():
    print("[STAGE 12] Loading test dataset partitions...")
    norm_path = Path("data/processed/normal_windows.npz")
    fault_path = Path("data/processed/inner_race_fault_windows.npz")
    scaler_path = Path("data/scaler/scaler_params.json")
    
    norm_windows = np.load(norm_path)['data']
    fault_windows = np.load(fault_path)['data']
    
    # Select sample 1800 from Normal (in Test set) and sample 1500 from Fault (in Test set)
    win_normal = norm_windows[1800].astype(np.float32) # shape: (512, 3)
    win_fault = fault_windows[1500].astype(np.float32)   # shape: (512, 3)
    
    # 1. Compute reference features in Python
    feat_norm_py = extract_features_single_window(win_normal)
    feat_fault_py = extract_features_single_window(win_fault)
    
    # 2. Load Scaler parameters
    with open(scaler_path, 'r') as f:
        scaler = json.load(f)
    mean = np.array(scaler['mean'], dtype=np.float32)
    scale = np.array(scaler['scale'], dtype=np.float32)
    
    # Standardize
    scaled_norm = (feat_norm_py - mean) * scale
    scaled_fault = (feat_fault_py - mean) * scale
    
    # 3. Compute PCA Reconstruction Score
    # Load PCA components and mean from pca_baseline.h or baseline module
    from src.baseline import PCAReconstructionAnomalyDetector
    split_data = np.load("data/processed/split_data.npz")
    pca_detector = PCAReconstructionAnomalyDetector(n_components=5)
    pca_detector.fit(split_data['X_train'])
    
    score_norm = float(pca_detector.compute_score(scaled_norm.reshape(1, -1))[0])
    score_fault = float(pca_detector.compute_score(scaled_fault.reshape(1, -1))[0])
    
    print(f"  -> Normal Window Reference Score (Python) : {score_norm:.4f}")
    print(f"  -> Fault Window Reference Score (Python)  : {score_fault:.4f}")
    
    # 4. Generate C Header
    header_content = [
        "/*",
        " * ZENTRA TinyML - Golden Test Vectors (Tahap 12)",
        " * Auto-generated by generate_golden_vectors.py",
        " * Contains exact raw vibration windows and Python reference outputs for parity validation.",
        " */",
        "",
        "#ifndef GOLDEN_TEST_VECTOR_H_",
        "#define GOLDEN_TEST_VECTOR_H_",
        "",
        "#include <stdint.h>",
        "",
        f"// Python Reference Scores",
        f"#define GOLDEN_NORMAL_PCA_SCORE_PY   {score_norm:.6f}f",
        f"#define GOLDEN_FAULT_PCA_SCORE_PY    {score_fault:.6f}f",
        "",
        "// 1. Raw Normal Window (512 samples x 3 channels)",
        "static const float GOLDEN_NORMAL_RAW_X[512] = {"
    ]
    
    def format_array_lines(arr, indent=4, per_line=8):
        lines = []
        for i in range(0, len(arr), per_line):
            chunk = arr[i:i+per_line]
            formatted = ", ".join(f"{v:.6f}f" for v in chunk)
            if i + per_line < len(arr):
                formatted += ","
            lines.append(" " * indent + formatted)
        return lines

    header_content.extend(format_array_lines(win_normal[:, 0]))
    header_content.append("};")
    header_content.append("")
    header_content.append("static const float GOLDEN_NORMAL_RAW_Y[512] = {")
    header_content.extend(format_array_lines(win_normal[:, 1]))
    header_content.append("};")
    header_content.append("")
    header_content.append("static const float GOLDEN_NORMAL_RAW_Z[512] = {")
    header_content.extend(format_array_lines(win_normal[:, 2]))
    header_content.append("};")
    header_content.append("")

    header_content.append("// 2. Raw Fault Window (512 samples x 3 channels)")
    header_content.append("static const float GOLDEN_FAULT_RAW_X[512] = {")
    header_content.extend(format_array_lines(win_fault[:, 0]))
    header_content.append("};")
    header_content.append("")
    header_content.append("static const float GOLDEN_FAULT_RAW_Y[512] = {")
    header_content.extend(format_array_lines(win_fault[:, 1]))
    header_content.append("};")
    header_content.append("")
    header_content.append("static const float GOLDEN_FAULT_RAW_Z[512] = {")
    header_content.extend(format_array_lines(win_fault[:, 2]))
    header_content.append("};")
    header_content.append("")

    header_content.append("// 3. Python Extracted Reference Features (60 elements)")
    header_content.append("static const float GOLDEN_NORMAL_FEATURES_PY[60] = {")
    header_content.extend(format_array_lines(feat_norm_py))
    header_content.append("};")
    header_content.append("")
    header_content.append("static const float GOLDEN_FAULT_FEATURES_PY[60] = {")
    header_content.extend(format_array_lines(feat_fault_py))
    header_content.append("};")
    header_content.append("")
    header_content.append("#endif // GOLDEN_TEST_VECTOR_H_")
    
    out_path = Path("firmware/include/golden_test_vector.h")
    out_path.write_text("\n".join(header_content))
    print(f"[SUCCESS] Exported Golden Test Vectors to {out_path} ({out_path.stat().st_size} bytes)")

if __name__ == "__main__":
    generate_golden_vectors()
